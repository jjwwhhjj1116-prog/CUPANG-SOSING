const version = '2026-10-19T00:00:00.000Z', next = '2026-10-19T00:00:00.001Z';
const deferred = () => { let resolve; const promise = new Promise(done => { resolve = done; }); return { promise, resolve }; };
const turn = () => new Promise(resolve => setImmediate(resolve));
const nodes = value => Array.isArray(value) ? value.flatMap(nodes) : value && typeof value === 'object' ? [value, ...nodes(value.props?.children)] : [];
const text = value => Array.isArray(value) ? value.map(text).join('') : value && typeof value === 'object' ? text(value.props?.children) : value == null ? '' : String(value);
const sameDeps = (a, b) => Array.isArray(a) && Array.isArray(b) && a.length === b.length && a.every((value, index) => Object.is(value, b[index]));
const optionTask = (optionId, productId = 'product') => ({ productId, productTitle: '검수 상품', optionId, optionLabel: optionId === 'black' ? '블랙' : '블루', profileId: 'profile',
  categoryContext: { source: 'profile', profileId: 'profile', categoryId: '81452', categoryPath: ['스포츠', '보호대'] }, productVersion: version });
const createPlan = (productId, empty) => ({ scope: { ownerId: 'owner', company: { code: 'A01464742', name: '와이홉' } },
  settings: { translateImages: false }, messages: [], tasks: empty ? [] : ['black', 'blue'].map(id => optionTask(id, productId)) });

/** Runs the actual wrapper with dependency-aware ordered hook/effect slots.
 * Only the read-only planner/refresh and ProductLabelEditor boundary are mocks.
 * This test cannot call a model, generate a PNG, save a label or transmit data. */
function harness({ autoGenerateDraft = false, empty = false, planGate, refreshGate } = {}) {
  const slots = [], layouts = [], effects = [], calls = [], busy = [], pending = [];
  let cursor = 0, dirty = true, tree, closed = false, late = 0, failRefresh = null, refreshVersion = version, refreshWait = refreshGate;
  let props = { products: [{ id: 'product', title: '검수 상품' }], autoGenerateDraft, onBusyChange: value => busy.push(value), onPendingChange: value => pending.push(value) };
  const enqueue = (queue, create, deps) => {
    const index = cursor++, previous = slots[index];
    if (!previous || !sameDeps(previous.deps, deps)) {
      const slot = { deps, create, kind: queue === layouts ? 'layout' : 'effect', cleanup: null }; slots[index] = slot;
      queue.push(() => { previous?.cleanup?.(); slot.cleanup = create(); });
    }
  };
  const hooks = {
    useState(initial) { const index = cursor++; if (!(index in slots)) slots[index] = { value: typeof initial === 'function' ? initial() : initial };
      return [slots[index].value, value => { if (closed) { late++; return; } const result = typeof value === 'function' ? value(slots[index].value) : value;
        if (!Object.is(result, slots[index].value)) { slots[index].value = result; dirty = true; } }]; },
    useRef(initial) { const index = cursor++; return slots[index] ?? (slots[index] = { current: initial }); },
    useEffect(create, deps) { enqueue(effects, create, deps); }, useLayoutEffect(create, deps) { enqueue(layouts, create, deps); },
    useCallback(callback, deps) { const index = cursor++, previous = slots[index]; if (!previous || !sameDeps(previous.deps, deps)) slots[index] = { callback, deps }; return slots[index].callback; },
  };
  function Child() { throw Error('ProductLabelEditor must remain an inert boundary in this test.'); }
  const helpers = {
    async planBatchLabelDraft(products, signal) { calls.push({ kind: 'plan', products: structuredClone(products), signal }); await planGate?.promise; return createPlan(products[0]?.id ?? 'product', empty); },
    async refreshBatchLabelDraftTask(selected, plan, signal) { calls.push({ kind: 'refresh', selected, plan, signal }); await refreshWait?.promise; if (failRefresh) throw Error(failRefresh); return { productVersion: refreshVersion }; },
  };
  const exports = {};
  vm.runInNewContext(ts.transpileModule(fs.readFileSync(new URL('../app/components/batch-label-draft-panel.tsx', import.meta.url), 'utf8'),
    { fileName: 'batch-label-draft-panel.tsx', compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, jsx: ts.JsxEmit.ReactJSX } }).outputText,
  { exports, AbortController, Error, structuredClone, require(name) {
    if (name === 'react') return hooks;
    if (name === 'react/jsx-runtime') return { jsx: (type, props, key) => ({ type, props, key }), jsxs: (type, props, key) => ({ type, props, key }) };
    if (name === '@/app/batch-label-draft') return helpers;
    if (name === '@/app/components/product-label-editor') return { ProductLabelEditor: Child };
    throw Error(`Unexpected dependency ${name}`);
  } });
  function render() {
    if (closed) return tree;
    for (let index = 0; dirty && index < 30; index++) {
      dirty = false; cursor = 0; tree = exports.BatchLabelDraftPanel(props);
      layouts.splice(0).forEach(run => run()); effects.splice(0).forEach(run => run());
      if (index === 29 && dirty) throw Error('Wrapper render did not settle.');
    }
    return tree;
  }
  const h = { calls, busy, pending, render,
    child() { return nodes(render()).find(node => node.type === Child); },
    button(label) { return nodes(render()).find(node => node.type === 'button' && text(node) === label); },
    task(label = '블랙') { return nodes(render()).find(node => node.type === 'button' && text(node).endsWith(`· ${label}`)); },
    async idle() { for (let index = 0; index < 8; index++) { render(); await turn(); } return render(); },
    update(value) { props = { ...props, ...value }; dirty = true; return render(); },
    fail(value) { failRefresh = value; }, savedVersion(value) { refreshVersion = value; }, holdRefresh(value) { refreshWait = value; },
    replayEffects() { render(); const committed = slots.filter(slot => slot?.create);
      for (const kind of ['layout', 'effect']) committed.filter(slot => slot.kind === kind).forEach(slot => slot.cleanup?.());
      for (const kind of ['layout', 'effect']) committed.filter(slot => slot.kind === kind).forEach(slot => { slot.cleanup = slot.create(); }); return render(); },
    get late() { return late; },
    close() { if (closed) return; closed = true; slots.forEach(slot => slot?.cleanup?.()); },
  }; return h;
}

test('idle label mode only inventories saved options and never mounts the model-capable child', async () => {
  const h = harness(); try {
    await h.idle(); assert.deepEqual(h.calls.map(call => call.kind), ['plan']); assert.equal(h.child(), undefined);
    assert.match(text(h.render()), /포함 옵션 2개/);
    h.button('현재 설정·표시사항 목록 다시 확인').props.onClick(); await h.idle();
    assert.deepEqual(h.calls.map(call => call.kind), ['plan', 'plan']); assert.equal(h.child(), undefined);
  } finally { h.close(); }
});

test('explicit work-start opens only the first included option with autoGenerateDraft true once', async () => {
  const h = harness({ autoGenerateDraft: true }); try {
    await h.idle(); assert.deepEqual(h.calls.map(call => call.kind), ['plan', 'refresh']);
    assert.equal(h.child().props.optionId, 'black'); assert.equal(h.child().props.autoGenerateDraft, true);
    assert.equal(h.child().props.version, version); assert.equal(h.child().props.profileId, 'profile');
    assert.equal(h.calls[0].kind, 'plan'); await h.idle(); assert.equal(h.calls.length, 2);
    h.button('현재 설정·표시사항 목록 다시 확인').props.onClick(); await h.idle();
    assert.equal(h.child(), undefined); assert.equal(h.calls.filter(call => call.kind === 'refresh').length, 1);
  } finally { h.close(); }
});

