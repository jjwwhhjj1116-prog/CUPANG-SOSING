test('the previous editor cannot release an independent in-flight option refresh busy lock', async () => {
  const held = deferred(), h = harness({ autoGenerateDraft: true }); try {
    await h.idle(); const old = h.child(); h.holdRefresh(held); h.task('블루').props.onClick(); await h.idle();
    old.props.onBusyChange(false); old.props.onDirtyChange(true); old.props.onSavedView({ productVersion: next }); await h.idle();
    assert.equal(h.busy.at(-1), true); assert.equal(h.render().props['data-workspace-saving'], true); assert.equal(h.child().props.version, version);
    held.resolve(); await h.idle(); assert.equal(h.child().props.optionId, 'blue'); assert.equal(h.busy.at(-1), false); assert.equal(h.pending.at(-1), false);
  } finally { held.resolve(); h.close(); }
});

test('closing held inventory or option reads aborts them and ignores late data and child callbacks', async () => {
  for (const kind of ['plan', 'refresh']) {
    const held = deferred(), h = harness(kind === 'plan' ? { planGate: held } : { autoGenerateDraft: true, refreshGate: held });
    await h.idle(); const request = h.calls.at(-1); assert.equal(request.kind, kind); h.close(); assert.equal(request.signal.aborted, true);
    held.resolve(); await turn(); await turn(); assert.equal(h.late, 0); assert.equal(h.busy.at(-1), false); assert.equal(h.pending.at(-1), false);
  }
  const h = harness({ autoGenerateDraft: true }); await h.idle(); const child = h.child(); h.close();
  child.props.onSavedView({ productVersion: next }); child.props.onBusyChange(true); child.props.onDirtyChange(true); assert.equal(h.late, 0);
});

test('a changed product cohort aborts the previous read and does not adopt its old child', async () => {
  const held = deferred(), h = harness({ refreshGate: held }); try {
    await h.idle(); h.task().props.onClick(); await h.idle(); const old = h.calls.at(-1);
    h.update({ products: [{ id: 'other-product', title: '다른 검수 상품' }] }); await h.idle(); assert.equal(old.signal.aborted, true);
    held.resolve(); await h.idle(); assert.equal(h.child(), undefined); assert.equal(h.busy.at(-1), false);
    assert.equal(h.calls.filter(call => call.kind === 'plan').length, 2); assert.equal(h.calls.filter(call => call.kind === 'plan').at(-1).products[0].id, 'other-product');
  } finally { held.resolve(); h.close(); }
});

