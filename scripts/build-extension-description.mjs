import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
import {build} from 'esbuild';
const root=new URL('../',import.meta.url),target=new URL('extensions/supplier-hub/alibaba-description.mjs',root);
const result=await build({entryPoints:[fileURLToPath(new URL('app/alibaba-description.ts',root))],bundle:true,write:false,format:'esm',platform:'browser',target:'chrome120',minify:true,legalComments:'inline'});
const content='// Generated by scripts/build-extension-description.mjs from app/alibaba-description.ts.\n// parse5 and entities licenses: mobile-public.LICENSE.txt\n'+result.outputFiles[0].text;
if(process.argv.includes('--check')){
 if(fs.readFileSync(target,'utf8').replace(/\r\n/g,'\n')!==content)throw Error('상품 상세 HTML 수집 모듈을 다시 빌드해주세요.');
}else fs.writeFileSync(target,content);
console.log('Chrome 상품 상세 HTML 수집 모듈 '+(process.argv.includes('--check')?'검사':'빌드')+' 완료');
