import fs from 'node:fs';
import { createHash } from 'node:crypto';

// Compile recorded, visible Supplier Hub fields. This script makes no network
// requests and never infers fields for an unobserved category.
const evidence = JSON.parse(fs.readFileSync('docs/supplier-hub-product-schemas-2026-09-23.json', 'utf8'));
const catalog = JSON.parse(fs.readFileSync('docs/supplier-hub-category-ids-2026-09-22.json', 'utf8'));
const exposedIds = { '색상': 'color', '수량': 'quantity', '사이즈': 'size', '단 수': 'optionLevels' };
const notices = {
  '품명 및 모델명': 'noticeNameModel', '재질': 'noticeMaterial', '구성품': 'noticeComponents',
  '크기': 'noticeDimensions', '출시년월': 'noticeReleaseDate', '제조자(수입자)': 'noticeManufacturerImporter',
  '제조국': 'noticeCountryOfOrigin', '수입신고 문구 여부': 'noticeImportDeclaration',
  '품질보증기준': 'noticeQualityAssurance', 'A/S 책임자와 전화번호': 'noticeServiceContact',
};
const schemas = {};
const mappingFields = {};
for (const record of evidence.records) {
  const { categoryId, path, observedAt } = record;
  if (Object.hasOwn(schemas, categoryId)) throw Error(`Duplicate category ${categoryId}`);
  if (!catalog.categoryIds.some(item => item.categoryId === categoryId && JSON.stringify(item.path) === JSON.stringify(path))) throw Error(`Unverified path ${categoryId}`);
  const priceIndex = record.columns.findIndex(column => column.label === '공급가 *');
  if (priceIndex < 1) throw Error(`Missing option boundary ${categoryId}`);
  const exposed = record.columns.slice(0, priceIndex).map(column => {
    const label = column.label.replace(/\s*\*\s*$/, '');
    const id = exposedIds[label];
    if (!id) throw Error(`Unmapped exposed attribute ${categoryId}/${label}`);
    return { id, label, required: column.label.endsWith('*') };
  });
  const hidden = record.hidden.map(item => {
    if (!item.label || !['input', 'select'].includes(item.type)) throw Error(`Invalid field ${categoryId}`);
    if (item.type === 'select' && (!item.choices?.length || new Set(item.choices.map(choice => choice.value)).size !== item.choices.length)) throw Error(`Invalid choices ${categoryId}/${item.label}`);
    const id = `hub_${categoryId}_${createHash('sha256').update(item.label).digest('hex').slice(0, 12)}`;
    if (categoryId !== '80719') mappingFields[id] = `${path.at(-1)}: ${item.label}`;
    return { id, label: item.label, type: item.type === 'select' ? 'select' : 'text', placeholder: item.placeholder,
      ...(item.choices ? { choices: item.choices } : {}) };
  });
  const noticeFields = (record.noticeLabels ?? []).map(label => {
    if (!Object.hasOwn(notices, label)) throw Error(`Unmapped notice ${categoryId}/${label}`);
    return { id: notices[label], label };
  });
  schemas[categoryId] = { path, observedAt, exposed, hidden, notices: noticeFields,
    maxIncludedOptions: record.maxIncludedOptions ?? null,
    salePriceMustCoverSupply: record.columns.some(column => column.label === '쿠팡 판매가 *' && column.help.includes('공급가보다 금액이 작을 수 없습니다')),
  };
}
const types = `// Generated by scripts/generate-hub-product-schemas.mjs from recorded UI evidence.\nexport type HubProductSchema = { path: string[]; observedAt: string; exposed: { id: string; label: string; required: boolean }[]; hidden: { id: string; label: string; type: 'text' | 'select'; placeholder: string; choices?: {value: string; label: string}[] }[]; notices: {id: string; label: string}[]; maxIncludedOptions: number | null; salePriceMustCoverSupply: boolean };\n`;
fs.writeFileSync('app/hub-product-schemas.ts', types + 'export const hubProductSchemas: Readonly<Record<string, HubProductSchema>> = ' + JSON.stringify(schemas, null, 2) + ';\n');
const sourcePath = 'app/category-profiles.ts';
let source = fs.readFileSync(sourcePath, 'utf8');
const generated = ['  // BEGIN OBSERVED HUB MAPPING FIELDS', '  optionLevels: \'관찰 카테고리: 단 수\',', ...Object.entries(mappingFields).map(([id, label]) => `  ${JSON.stringify(id)}: ${JSON.stringify(label)},`), '  // END OBSERVED HUB MAPPING FIELDS'].join('\n');
if (source.includes('// BEGIN OBSERVED HUB MAPPING FIELDS')) source = source.replace(/  \/\/ BEGIN OBSERVED HUB MAPPING FIELDS[\s\S]*?  \/\/ END OBSERVED HUB MAPPING FIELDS/, generated);
else source = source.replace('export const categoryFields = {', 'export const categoryFields = {\n' + generated);
fs.writeFileSync(sourcePath, source);
console.log(`Compiled ${Object.keys(schemas).length} observed category schemas and ${Object.keys(mappingFields).length} scoped mapping fields.`);
