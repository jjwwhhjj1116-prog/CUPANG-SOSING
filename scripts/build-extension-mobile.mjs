import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
import {build} from 'esbuild';
const root=new URL('../',import.meta.url);
const readText=target=>fs.readFileSync(target,'utf8').replace(/\r\n/g,'\n');
const result=await build({entryPoints:[fileURLToPath(new URL('deployment/extension-mobile-entry.ts',root))],bundle:true,write:false,format:'esm',platform:'browser',target:'chrome120',minify:true,legalComments:'inline',tsconfig:fileURLToPath(new URL('tsconfig.json',root))});
const content='// Generated by scripts/build-extension-mobile.mjs from the shared public source parser.\n// parse5 and entities licenses: mobile-public.LICENSE.txt\n'+result.outputFiles[0].text;
const target=new URL('extensions/supplier-hub/mobile-public.mjs',root);
const licenses=['parse5','entities'].map(name=>name+'\n'+readText(new URL('node_modules/'+name+'/LICENSE',root))).join('\n\n');
const licenseTarget=new URL('extensions/supplier-hub/mobile-public.LICENSE.txt',root);
if(process.argv.includes('--check')){
 if(readText(target)!==content)throw Error('공개 상품 수집 모듈을 다시 빌드해주세요.');
 if(readText(licenseTarget)!==licenses)throw Error('공개 상품 수집 모듈의 라이선스를 다시 빌드해주세요.');
}else{fs.writeFileSync(target,content);fs.writeFileSync(licenseTarget,licenses);}
console.log('Chrome 공개 상품 수집 모듈 '+(process.argv.includes('--check')?'검사':'빌드')+' 완료');
