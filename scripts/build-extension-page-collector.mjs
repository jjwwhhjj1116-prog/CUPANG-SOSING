import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
import {build} from 'esbuild';
const root=new URL('../',import.meta.url),target=new URL('extensions/supplier-hub/page-collector.js',root);
const result=await build({entryPoints:[fileURLToPath(new URL('deployment/extension-page-collector.mjs',root))],bundle:true,write:false,format:'iife',platform:'browser',target:'chrome120',minify:true,legalComments:'none'});
const content='// Generated by scripts/build-extension-page-collector.mjs.\n'+result.outputFiles[0].text;
if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8').replace(/\r\n/g,'\n')!==content)throw Error('상품 수집 버튼을 다시 빌드해주세요.');}else fs.writeFileSync(target,content);
console.log('Chrome 상품 수집 버튼 '+(process.argv.includes('--check')?'검사':'빌드')+' 완료');
