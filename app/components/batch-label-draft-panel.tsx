'use client';

import { useCallback, useEffect, useLayoutEffect, useRef, useState } from 'react';
import { planBatchLabelDraft, refreshBatchLabelDraftTask, type BatchLabelDraftPlan, type BatchLabelDraftTask } from '@/app/batch-label-draft';
import { ProductLabelEditor } from '@/app/components/product-label-editor';

type Props = { products: { id: string; title: string }[]; autoGenerateDraft?: boolean;
  onBusyChange?: (busy: boolean) => void; onPendingChange?: (pending: boolean) => void };

/** Reuse the actual stage-six editor: model suggestions remain local until
 * review/save, and PNG generation/quotation attachment stay explicit. */
export function BatchLabelDraftPanel(props: Props) {
  const [plan, setPlan] = useState<BatchLabelDraftPlan | null>(null), [active, setActive] = useState<BatchLabelDraftTask | null>(null);
  const [version, setVersion] = useState(''), [busy, setBusy] = useState(false), [pending, setPending] = useState(false);
  const [error, setError] = useState(''), [initial, setInitial] = useState(true), [autoGenerate, setAutoGenerate] = useState(false);
  const [generation, setGeneration] = useState(0);
  const controls = useRef(props), alive = useRef(true), request = useRef<AbortController | null>(null);
  const childBusy = useRef(false), childPending = useRef(false), currentPlan = useRef<BatchLabelDraftPlan | null>(null);
  const selectedTask = useRef<BatchLabelDraftTask | null>(null), selectionVersion = useRef(0), selectionProducts = useRef('');
  const productKey = JSON.stringify(props.products.map(product => [product.id, product.title]));
  useLayoutEffect(() => { controls.current = props; }, [props]);
  const publishBusy = useCallback((value: boolean) => { childBusy.current = value; setBusy(value); controls.current.onBusyChange?.(value); }, []);
  const publishPending = useCallback((value: boolean) => { childPending.current = value; setPending(value); controls.current.onPendingChange?.(value); }, []);
  const locked = () => !!request.current || childBusy.current || childPending.current;
  useEffect(() => { alive.current = true; return () => { alive.current = false; request.current?.abort(); controls.current.onBusyChange?.(false); controls.current.onPendingChange?.(false); }; }, []);
  async function openTask(task: BatchLabelDraftTask, value: BatchLabelDraftPlan, start: boolean, controller: AbortController) {
    const view = await refreshBatchLabelDraftTask(task, value, controller.signal);
    if (!alive.current || controller.signal.aborted || request.current !== controller) return;
    selectedTask.current = task; selectionVersion.current++;
    selectionProducts.current = JSON.stringify(controls.current.products.map(product => [product.id, product.title]));
    setVersion(view.productVersion); setActive(task); setAutoGenerate(start); setGeneration(selectionVersion.current);
  }
  async function load(start: boolean) {
    if (locked()) return;
    const controller = new AbortController(); request.current = controller; publishBusy(true); setError('');
    try {
      const value = await planBatchLabelDraft(controls.current.products, controller.signal);
      if (!alive.current || controller.signal.aborted || request.current !== controller) return;
      currentPlan.current = value; selectedTask.current = null; setPlan(value); setActive(null);
      if (start && value.tasks[0]) await openTask(value.tasks[0], value, true, controller);
    } catch (cause) { if (alive.current && !controller.signal.aborted) setError(cause instanceof Error ? cause.message : '표시사항 작업 목록을 읽지 못했습니다.'); }
    finally { if (request.current === controller) { request.current = null; if (alive.current) { publishBusy(false); setInitial(false); } } }
  }
  useEffect(() => {
    let cancelled = false;
    void Promise.resolve().then(() => {
      if (cancelled) return;
      selectedTask.current = null; selectionVersion.current++; setActive(null); currentPlan.current = null;
      childBusy.current = false; childPending.current = false; publishPending(false);
      void load(controls.current.autoGenerateDraft === true);
    });
    return () => { cancelled = true; request.current?.abort(); request.current = null; };
    // Each explicit cohort owns its drafts; idle reads never invoke a model.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [productKey]);
  async function select(task: BatchLabelDraftTask) {
    const value = currentPlan.current;
    if (locked() || !value) return;
    const controller = new AbortController(); request.current = controller; publishBusy(true); setError('');
    try { await openTask(task, value, true, controller); }
    catch (cause) { if (alive.current && !controller.signal.aborted) setError(cause instanceof Error ? cause.message : '최신 표시사항을 확인하지 못했습니다.'); }
    finally { if (request.current === controller) { request.current = null; if (alive.current) publishBusy(false); } }
  }
  const currentChild = () => alive.current && !request.current && selectedTask.current === active && selectionVersion.current === generation
    && selectionProducts.current === JSON.stringify(controls.current.products.map(product => [product.id, product.title]));
  return <section className="panel-stack" aria-label="선택 상품 표시사항 초안 작업" data-workspace-saving={busy} data-workspace-dirty={pending}>
    <h3>한글표시사항 초안 작성·검토</h3>
    <p>포함 옵션의 상품 원문과 저장 설정으로 내용량·재질·상품 유형의 AI 초안을 준비합니다. 직접 수정한 값과 공란은 유지하며, 초안은 검토 후 정보 저장하기를 눌러야 반영됩니다.</p>
    <p>나머지 표시 항목도 확인·수정한 뒤 PNG를 생성하고 견적서에 연결하세요. 등록전송은 최종 견적서에서 진행합니다.</p>
    {initial && <p role="status">현재 계정의 설정과 표시사항 목록을 읽고 있습니다…</p>}
    {plan?.messages.map((item, index) => <p role="status" key={`${item.productId}:${index}`}>{props.products.find(product => product.id === item.productId)?.title ?? item.productId} · {item.message}</p>)}
    {error && <p role="alert">{error}</p>}
    {plan && <p>포함 옵션 {plan.tasks.length}개 · 초안 검토 후 같은 옵션의 표시사항과 견적서에 연결합니다.</p>}
    <div className="quote-actions">{plan?.tasks.map((task, index) => <button type="button" className="btn ghost" key={`${task.productId}:${task.optionId}`} disabled={busy || pending}
      aria-pressed={active === task} onClick={() => void select(task)}>{index + 1}. {task.productTitle} · {task.optionLabel}</button>)}</div>
    <button type="button" className="btn ghost" disabled={busy || pending} onClick={() => void load(false)}>현재 설정·표시사항 목록 다시 확인</button>
    {active && <ProductLabelEditor key={`${active.productId}:${active.optionId}:${generation}`} productId={active.productId}
      optionId={active.optionId} profileId={active.profileId ?? undefined} version={version} active autoGenerateDraft={autoGenerate}
      onBusyChange={value => { if (currentChild()) publishBusy(value); }} onDirtyChange={value => { if (currentChild()) publishPending(value); }}
      onSavedView={view => { if (currentChild()) setVersion(view.productVersion); }} />}
    {pending && <p role="status">수정한 표시사항을 저장하거나 입력을 취소하면 다른 옵션으로 이동할 수 있습니다. 저장 결과 확인이 필요한 요청은 먼저 현재 옵션에서 확인해주세요.</p>}
  </section>;
}
